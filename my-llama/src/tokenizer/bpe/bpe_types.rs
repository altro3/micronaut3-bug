pub type TokenId = u32;
pub type BpeRank = u32;

/// Компактный узел двусвязного списка BPE для линейного массива.
/// Размер структуры — ровно 8 байт (u32 + u16 + u16).
/// Позволяет упаковать 8 таких узлов в одну 64-байтную кэш-линию процессора Intel!
#[derive(Clone, Copy)]
#[repr(C, packed)]
pub struct FlatBpeNode {
    pub id: u32,     // ID текущего токена
    pub next: u16,   // Индекс следующего узла в чанке (0xFFFF — конец)
    pub prev: u16,   // Индекс предыдущего узла в чанке (0xFFFF — начало)
}
