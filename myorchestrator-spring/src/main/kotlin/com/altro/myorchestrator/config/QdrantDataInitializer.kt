package com.altro.myorchestrator.config

import com.altro.myorchestrator.model.Platform
import org.springframework.ai.document.Document
import org.springframework.ai.vectorstore.VectorStore
import org.springframework.boot.CommandLineRunner
import org.springframework.stereotype.Component
import java.util.UUID

@Component
class QdrantDataInitializer(
    private val vectorStore: VectorStore
) : CommandLineRunner {

    override fun run(vararg args: String) {
        val documents = listOf(
            Document(
                UUID.randomUUID().toString(),
                """
                Правила YANDEX_DIRECT:
                1. ТРЕБОВАНИЕ К КОНТЕНТУ: Заголовок объявления до 56 символов. Текст объявления до 81 символа. Запрещен CapsLock. Текст должен быть строго на русском языке, без синтаксических ошибок.
                2. ОБЯЗАТЕЛЬНЫЙ ВОЗРАСТНОЙ ЦЕНЗ: Реклама категории 'Автосервисы и ремонт автомобилей (включая PDR)' в Яндекс.Директ требует обязательной возрастной маркировки (например: 0+, 16+, 18+). Агенту КАТЕГОРИЧЕСКИ ЗАПРЕЩЕНО самостоятельно придумывать, угадывать или проставлять возрастной ценз по умолчанию! Этот слот считается ПУСТЫМ, пока пользователь сам явно не назовет маркировку в чате.
                """.trimIndent(),
                mapOf("platform" to Platform.YANDEX_DIRECT.name)
            ),

            Document(
                UUID.randomUUID().toString(),
                """
                Правила VK_ADS:
                Заголовок объявления от 3 до 30 символов. Основной текст до 90 символов. Запрещены эмодзи в заголовках. Обращение к пользователю строго на 'Вы'. Кампания инициируется в холостом режиме.
                """.trimIndent(),
                mapOf("platform" to Platform.VK_ADS.name)
            ),

            Document(
                UUID.randomUUID().toString(),
                """
                Закон о маркировке интернет-рекламы в РФ (Федеральный закон № 347-ФЗ):
                1. СТРОГОЕ ТРЕБОВАНИЕ К ИНН: Любое рекламное объявление обязано содержать пометку 'Реклама' и указание РЕАЛЬНОГО ИНН рекламодателя (например: 'Реклама. ИНН 5406123456'). 
                2. КАТЕГОРИЧЕСКИЙ ЗАПРЕЩЕНО ГЕНЕРИРОВАТЬ ФЕЙКИ: Агенту строго запрещено выдумывать ИНН от себя или использовать фейковые заглушки/коды регионов (такие как 5400000000, 0000000000 или 1234567890). 
                3. БЛОКИРОВКА АВТОМАТИЗАЦИИ: Пока реальный ИНН не предоставлен пользователем в явном виде, данный слот считается ПУСТЫМ. Согласно алгоритму валидации, инструменты сохранения креативов и публикации должны быть немедленно заблокированы, а Агент обязан выйти в чат и запросить реальный ИНН у пользователя.
                4. ОБЯЗАТЕЛЬНЫЙ ВОЗРАСТНОЙ ЦЕНЗ АУДИТОРИИ: Указание возрастной категории пользователей (например: 0+, 6+, 12+, 16+, 18+) является СТРОГО ОБЯЗАТЕЛЬНЫМ параметром для настройки этой кампании. Агенту КАТЕГОРИЧЕСКИ ЗАПРЕЩЕНО самостоятельно выдумывать, угадывать или проставлять возрастной ценз по умолчанию. Пока пользователь сам явно не назовет возрастную категорию в чате, этот слот считается полностью ПУСТЫМ и ОТСУТСТВУЮЩИМ в системе.
                """.trimIndent(),
                mapOf("platform" to "ALL")
            ),
        )

        try {
            vectorStore.accept(documents)
        } catch (e: Exception) {
            println("Ошибка инициализации Qdrant (возможно, коллекция уже создана): ${e.message}")
        }
    }
}
